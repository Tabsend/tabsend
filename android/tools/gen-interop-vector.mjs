/**
 * Interop test-vector generator — the TS/libsodium SIDE of the Android crypto proof.
 *
 * Runs against the SAME `libsodium-wrappers` the browser extension uses (see
 * extension/src/lib/crypto.ts), with the SAME conventions:
 *   - public/secret keys as STANDARD base64,
 *   - crypto_box (X25519 + XSalsa20-Poly1305) via crypto_box_easy,
 *   - keyId = base64url_nopad( SHA-256( utf8( pubkeyBase64String ) ) ),
 *   - nonce + ciphertext as STANDARD base64,
 *   - the sealed plaintext is JSON.stringify(SendPayload).
 *
 * We pin the sender/recipient keypairs and the nonce so the emitted ciphertext is
 * DETERMINISTIC and can be committed. The Android CryptoBox, given the identical
 * keys + nonce + plaintext, must reproduce this ciphertext BYTE-FOR-BYTE (and must
 * open it back to the plaintext). That is the byte-for-byte interop guarantee.
 *
 * Regenerate:  node android/tools/gen-interop-vector.mjs
 * (only needed if the crypto contract in shared/ ever changes — it shouldn't.)
 */
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { dirname, join } from 'node:path'
import { createRequire } from 'node:module'

// The monorepo uses pnpm; libsodium-wrappers (the extension's crypto dep) lives in
// the pnpm store, not at this script's node_modules. Resolve it from the repo root.
const require = createRequire(pathToFileURL(join(process.cwd(), 'noop.js')))
const _sodium = require(
  './node_modules/.pnpm/libsodium-wrappers@0.7.16/node_modules/libsodium-wrappers/dist/modules/libsodium-wrappers.js',
)

const b64 = (u8) => Buffer.from(u8).toString('base64')
const b64ToBytes = (s) => new Uint8Array(Buffer.from(s, 'base64'))
const keyId = (pubB64) => createHash('sha256').update(pubB64).digest('base64url')

await _sodium.ready
const sodium = _sodium

// Deterministic keypairs from fixed 32-byte seeds (stable across regenerations).
const seedSender = Buffer.alloc(32, 0x11)
const seedRecipient = Buffer.alloc(32, 0x22)
const sender = sodium.crypto_box_seed_keypair(new Uint8Array(seedSender))
const recipient = sodium.crypto_box_seed_keypair(new Uint8Array(seedRecipient))

const senderPub = b64(sender.publicKey)
const senderPriv = b64(sender.privateKey)
const recipientPub = b64(recipient.publicKey)
const recipientPriv = b64(recipient.privateKey)

// A fixed 24-byte nonce → deterministic ciphertext.
const nonceBytes = new Uint8Array(sodium.crypto_box_NONCEBYTES)
for (let i = 0; i < nonceBytes.length; i += 1) nonceBytes[i] = (i * 7 + 3) & 0xff
const nonce = b64(nonceBytes)

// A realistic SendPayload, sealed exactly as the extension does: JSON.stringify(payload).
const payload = {
  url: 'https://example.com/a?b=c&d=e#frag',
  title: 'Example — a tab in flight ✈️',
  sentAt: '2026-07-18T12:34:56.000Z',
}
const plaintext = JSON.stringify(payload)

const ciphertext = b64(
  sodium.crypto_box_easy(
    new TextEncoder().encode(plaintext),
    nonceBytes,
    b64ToBytes(recipientPub),
    b64ToBytes(senderPriv),
  ),
)

const vector = {
  _comment:
    'Interop test vector generated by android/tools/gen-interop-vector.mjs against libsodium-wrappers (the extension crypto). Android CryptoBox must reproduce `envelope.ciphertext` byte-for-byte from these keys+nonce+plaintext, and must open it back to `plaintext`.',
  alg: 'x25519-xsalsa20-poly1305/box',
  sender: { publicKey: senderPub, privateKey: senderPriv, keyId: keyId(senderPub) },
  recipient: { publicKey: recipientPub, privateKey: recipientPriv, keyId: keyId(recipientPub) },
  nonce,
  plaintext,
  // The envelope shape the extension puts on the wire (shared/src/types.ts EncryptedEnvelope).
  envelope: {
    alg: 'x25519-xsalsa20-poly1305/box',
    senderKeyId: keyId(senderPub),
    targetKeyId: keyId(recipientPub),
    nonce,
    ciphertext,
  },
}

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'app', 'src', 'test', 'resources')
const outPath = join(outDir, 'interop-vector.json')
writeFileSync(outPath, `${JSON.stringify(vector, null, 2)}\n`)
console.log('wrote', outPath)
console.log('senderKeyId  =', vector.sender.keyId)
console.log('targetKeyId  =', vector.recipient.keyId)
console.log('ciphertext   =', ciphertext)
