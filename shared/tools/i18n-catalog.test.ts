import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { GENERATED_NOTICE_KEY, messagesOf, readLanguage } from './i18n-catalog'

describe('the notice i18n-kit writes at the top of a translated file', () => {
  let dir = ''
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'tabsend-catalog-'))
    mkdirSync(join(dir, 'de'))
  })
  afterEach(() => rmSync(dir, { recursive: true, force: true }))

  it('is not read as a message', () => {
    writeFileSync(
      join(dir, 'de', 'send.json'),
      JSON.stringify({
        [GENERATED_NOTICE_KEY]: 'Generated by i18n-kit. Do not edit.',
        'send.done': { message: 'Gesendet' },
      }),
    )
    const files = readLanguage(dir, 'de')
    expect(Object.keys(files.send ?? {})).toEqual(['send.done'])
  })

  it('never reaches the bundle, even when a file is handed over unread', () => {
    const file = {
      [GENERATED_NOTICE_KEY]: 'Generated by i18n-kit. Do not edit.',
      'send.done': { message: 'Gesendet' },
    } as unknown as Parameters<typeof messagesOf>[0]
    expect(messagesOf(file)).toEqual({ 'send.done': 'Gesendet' })
  })

  it('still reports any other key that is not a message', () => {
    writeFileSync(
      join(dir, 'de', 'send.json'),
      JSON.stringify({ _other: 'stray', 'send.done': { message: 'Gesendet' } }),
    )
    expect(Object.keys(readLanguage(dir, 'de').send ?? {})).toEqual(['_other', 'send.done'])
  })
})
